//! Rust bindings for out-of-process native providers.
//!
//! The output is one self-contained module source: contract identity
//! constants for the protocol handshake, serde types for named types, state
//! and event payloads, a `Provider` trait with one method per command, and a
//! `dispatch` function that decodes a call's argument object the way the
//! shell sends it. It depends only on `serde` and `serde_json`, and uses only
//! `super::` paths, so it compiles wherever it is `include!`d.

use crate::contract::{
    BUILTIN_RESULT_TYPE, BaseType, CompiledContract, CompiledField, RUNTIME_METADATA_STATE_FIELDS,
    TypeExpr,
};
use std::collections::HashSet;
use std::fmt::Write;

const DERIVES: &str =
    "#[derive(Debug, Clone, Default, PartialEq, serde::Serialize, serde::Deserialize)]";

/// Generate the Rust provider bindings for `contract`.
///
/// Fails when two contract names map to the same Rust identifier, which the
/// contract grammar allows but Rust cannot express.
pub fn generate_rust_bindings(contract: &CompiledContract) -> Result<String, String> {
    let mut output = format!(
        "// GENERATED by MESH from {}@{} (Rust provider bindings); do not edit.\n\
         // schema={} policy={} behavior={}\n\n",
        contract.interface,
        contract.version,
        contract.schema_fingerprint,
        contract.policy_fingerprint,
        contract.behavior_fingerprint,
    );

    writeln!(
        output,
        "pub const INTERFACE: &str = {:?};",
        contract.interface
    )
    .unwrap();
    writeln!(
        output,
        "pub const VERSION: &str = \"{}\";",
        contract.version
    )
    .unwrap();
    writeln!(
        output,
        "pub const SCHEMA_FINGERPRINT: u64 = 0x{:016x};",
        contract.schema_fingerprint
    )
    .unwrap();
    writeln!(
        output,
        "pub const POLICY_FINGERPRINT: u64 = 0x{:016x};",
        contract.policy_fingerprint
    )
    .unwrap();
    writeln!(
        output,
        "pub const BEHAVIOR_FINGERPRINT: u64 = 0x{:016x};",
        contract.behavior_fingerprint
    )
    .unwrap();
    let features = contract
        .features
        .keys()
        .map(|name| format!("{name:?}"))
        .collect::<Vec<_>>()
        .join(", ");
    writeln!(output, "/// Optional features a provider may advertise.").unwrap();
    writeln!(output, "pub const FEATURES: &[&str] = &[{features}];\n").unwrap();

    output.push_str(RUNTIME_PRELUDE);
    if uses_blob(contract) {
        output.push_str(BLOB_HANDLE_PRELUDE);
    }

    let mut type_names = Names::default();
    let mut type_structs = Vec::new();
    for definition in contract.schemas.types.values() {
        let ident = type_names.claim_type(&pascal_ident(&definition.name), &definition.name)?;
        type_structs.push(record_struct(&ident, &definition.fields)?);
    }
    write_module(&mut output, "types", &type_structs);

    output.push_str("/// The state every provider publishes.\n");
    writeln!(output, "{DERIVES}\npub struct State {{").unwrap();
    let mut field_names = Names::default();
    for field in contract
        .schemas
        .state_fields
        .iter()
        .filter(|field| !RUNTIME_METADATA_STATE_FIELDS.contains(&field.name.as_str()))
    {
        if let Some(description) = &field.description {
            write_doc(&mut output, "    ", description);
        }
        if field.minimum.is_some() || field.maximum.is_some() {
            let bound = |value: &Option<serde_json::Number>| {
                value.as_ref().map(ToString::to_string).unwrap_or_default()
            };
            writeln!(
                output,
                "    /// The shell clamps this to {}..{}.",
                bound(&field.minimum),
                bound(&field.maximum)
            )
            .unwrap();
        }
        if let Some(feature) = contract.member_features.get(&field.name) {
            writeln!(
                output,
                "    /// Published only with the `{feature}` feature."
            )
            .unwrap();
        }
        let ident = field_names.claim(&snake_ident(&field.name), &field.name)?;
        write_field(
            &mut output,
            "    ",
            &ident,
            &field.name,
            &field.type_expr,
            "",
        );
    }
    output.push_str("}\n\n");

    let mut event_names = Names::default();
    let mut event_idents = Vec::new();
    let mut event_structs = Vec::new();
    for event in contract.schemas.events.iter() {
        let ident = event_names.claim_type(&pascal_ident(&event.name), &event.name)?;
        event_structs.push(record_struct(&ident, &event.payload)?);
        event_idents.push((ident, event.name.as_str()));
    }
    write_module(&mut output, "events", &event_structs);

    output.push_str(
        "/// An event a provider emits.\n#[derive(Debug, Clone, PartialEq)]\npub enum Event {\n",
    );
    for (ident, _) in &event_idents {
        writeln!(output, "    {ident}(events::{ident}),").unwrap();
    }
    output.push_str("}\n\nimpl Event {\n    pub fn name(&self) -> &'static str {\n");
    if event_idents.is_empty() {
        output.push_str("        match *self {}\n");
    } else {
        output.push_str("        match self {\n");
        for (ident, name) in &event_idents {
            writeln!(output, "            Self::{ident}(_) => {name:?},").unwrap();
        }
        output.push_str("        }\n");
    }
    output.push_str("    }\n\n    pub fn payload(&self) -> serde_json::Value {\n");
    if event_idents.is_empty() {
        output.push_str("        match *self {}\n");
    } else {
        output.push_str("        let payload = match self {\n");
        for (ident, _) in &event_idents {
            writeln!(
                output,
                "            Self::{ident}(payload) => serde_json::to_value(payload),"
            )
            .unwrap();
        }
        output.push_str(
            "        };\n        payload.expect(\"generated event payloads always serialize\")\n",
        );
    }
    output.push_str("    }\n}\n\n");

    output.push_str(
        "/// One handler per contract method. An `Err` settles the call as failed\n\
         /// with that message.\npub trait Provider {\n",
    );
    let mut method_names = Names::default();
    let mut methods = Vec::new();
    for method in contract.schemas.methods.iter() {
        let ident = method_names.claim(&snake_ident(&method.name), &method.name)?;
        if let Some(feature) = contract.member_features.get(&method.name) {
            writeln!(
                output,
                "    /// Called only when the provider advertises `{feature}`."
            )
            .unwrap();
        }
        let mut arg_names = Names::default();
        let mut args = Vec::new();
        for arg in method.args.iter() {
            args.push((arg_names.claim(&snake_ident(&arg.name), &arg.name)?, arg));
        }
        let params = args
            .iter()
            .map(|(ident, arg)| format!(", {ident}: {}", rust_type(&arg.type_expr, "")))
            .collect::<String>();
        let returns = method
            .returns
            .as_ref()
            .map(|returns| rust_type(returns, ""))
            .unwrap_or_else(|| "()".to_string());
        writeln!(
            output,
            "    fn {ident}(&mut self{params}) -> Result<{returns}, String>;"
        )
        .unwrap();
        methods.push((ident, method, args));
    }
    output.push_str("}\n\n");

    output.push_str(
        "/// Decode one call's argument object and run the matching handler,\n\
         /// returning the JSON result the shell validates against the contract.\n\
         pub fn dispatch<P: Provider + ?Sized>(\n    provider: &mut P,\n    method: &str,\n    args: serde_json::Value,\n) -> Result<serde_json::Value, DispatchError> {\n",
    );
    if methods.is_empty() {
        output.push_str("    let _ = (provider, args);\n");
    }
    output.push_str("    match method {\n");
    for (ident, method, args) in &methods {
        writeln!(output, "        {:?} => {{", method.name).unwrap();
        if args.is_empty() {
            output.push_str("            let _ = args;\n");
            writeln!(output, "            provider.{ident}()").unwrap();
        } else {
            output
                .push_str("            #[derive(serde::Deserialize)]\n            struct Args {\n");
            for (arg_ident, arg) in args {
                write_field(
                    &mut output,
                    "                ",
                    arg_ident,
                    &arg.name,
                    &arg.type_expr,
                    "",
                );
            }
            output.push_str("            }\n");
            writeln!(
                output,
                "            let args: Args = serde_json::from_value(args).map_err(|error| {{\n                DispatchError::InvalidArguments {{ method: {:?}, message: error.to_string() }}\n            }})?;",
                method.name
            )
            .unwrap();
            let call_args = args
                .iter()
                .map(|(arg_ident, _)| format!("args.{arg_ident}"))
                .collect::<Vec<_>>()
                .join(", ");
            writeln!(output, "            provider.{ident}({call_args})").unwrap();
        }
        writeln!(
            output,
            "                .map_err(|message| DispatchError::Failed {{ method: {:?}, message }})\n                .map(|result| serde_json::to_value(result).expect(\"generated results always serialize\"))",
            method.name
        )
        .unwrap();
        output.push_str("        }\n");
    }
    output.push_str(
        "        _ => Err(DispatchError::UnknownMethod(method.to_string())),\n    }\n}\n",
    );
    Ok(output)
}

const RUNTIME_PRELUDE: &str = "\
/// The contract's builtin `Result` type.
#[derive(Debug, Clone, Default, PartialEq, serde::Serialize, serde::Deserialize)]
pub struct CallResult {
    pub ok: bool,
    #[serde(default, skip_serializing_if = \"Option::is_none\")]
    pub error: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum DispatchError {
    UnknownMethod(String),
    InvalidArguments { method: &'static str, message: String },
    Failed { method: &'static str, message: String },
}

impl std::fmt::Display for DispatchError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::UnknownMethod(method) => write!(f, \"unknown method '{method}'\"),
            Self::InvalidArguments { method, message } => {
                write!(f, \"invalid arguments for '{method}': {message}\")
            }
            Self::Failed { method, message } => write!(f, \"'{method}' failed: {message}\"),
        }
    }
}

impl std::error::Error for DispatchError {}

";

const BLOB_HANDLE_PRELUDE: &str = "\
/// A `mesh-blob:sha256-…` handle to bytes the provider registered; contract
/// type `blob`.
#[derive(Debug, Clone, Default, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]
#[serde(transparent)]
pub struct BlobHandle(pub String);

";

fn uses_blob(contract: &CompiledContract) -> bool {
    let schemas = &contract.schemas;
    let is_blob = |expr: &TypeExpr| expr.base == BaseType::Blob;
    let fields_use_blob = |fields: &[CompiledField]| fields.iter().any(|f| is_blob(&f.type_expr));
    schemas.state_fields.iter().any(|f| is_blob(&f.type_expr))
        || schemas.methods.iter().any(|method| {
            fields_use_blob(&method.args) || method.returns.as_ref().is_some_and(is_blob)
        })
        || schemas.events.iter().any(|event| fields_use_blob(&event.payload))
        || schemas.types.values().any(|ty| fields_use_blob(&ty.fields))
}

/// A struct inside a generated submodule, whose path to the root is `super::`.
fn record_struct(ident: &str, fields: &[CompiledField]) -> Result<String, String> {
    if fields.is_empty() {
        return Ok(format!("    {DERIVES}\n    pub struct {ident} {{}}\n"));
    }
    let mut output = format!("    {DERIVES}\n    pub struct {ident} {{\n");
    write_fields(&mut output, "        ", fields, "super::")?;
    output.push_str("    }\n");
    Ok(output)
}

fn write_module(output: &mut String, name: &str, items: &[String]) {
    writeln!(output, "pub mod {name} {{").unwrap();
    output.push_str(&items.join("\n"));
    output.push_str("}\n\n");
}

fn write_fields(
    output: &mut String,
    indent: &str,
    fields: &[CompiledField],
    root: &str,
) -> Result<(), String> {
    let mut names = Names::default();
    for field in fields {
        let ident = names.claim(&snake_ident(&field.name), &field.name)?;
        write_field(output, indent, &ident, &field.name, &field.type_expr, root);
    }
    Ok(())
}

fn write_field(
    output: &mut String,
    indent: &str,
    ident: &str,
    wire_name: &str,
    type_expr: &TypeExpr,
    root: &str,
) {
    if ident.trim_start_matches("r#") != wire_name {
        writeln!(output, "{indent}#[serde(rename = {wire_name:?})]").unwrap();
    }
    if type_expr.optional {
        writeln!(
            output,
            "{indent}#[serde(default, skip_serializing_if = \"Option::is_none\")]"
        )
        .unwrap();
    }
    writeln!(
        output,
        "{indent}pub {ident}: {},",
        rust_type(type_expr, root)
    )
    .unwrap();
}

fn write_doc(output: &mut String, indent: &str, text: &str) {
    for line in text.lines() {
        writeln!(output, "{indent}/// {line}").unwrap();
    }
}

/// `root` is the path from the current module to the generated root module.
fn rust_type(expr: &TypeExpr, root: &str) -> String {
    let base = match &expr.base {
        BaseType::String => "String".to_string(),
        BaseType::Int => "i64".to_string(),
        BaseType::Float => "f64".to_string(),
        BaseType::Boolean => "bool".to_string(),
        BaseType::Blob => format!("{root}BlobHandle"),
        BaseType::Object => "serde_json::Map<String, serde_json::Value>".to_string(),
        BaseType::Any => "serde_json::Value".to_string(),
        BaseType::Named(name) if name == BUILTIN_RESULT_TYPE => format!("{root}CallResult"),
        BaseType::Named(name) => format!("{root}types::{}", pascal_ident(name)),
    };
    let base = if expr.array {
        format!("Vec<{base}>")
    } else {
        base
    };
    if expr.optional {
        format!("Option<{base}>")
    } else {
        base
    }
}

/// Tracks identifiers within one Rust namespace so two contract names that
/// sanitize to the same identifier are reported instead of miscompiling.
#[derive(Default)]
struct Names(HashSet<String>);

/// Types the generated fields name unqualified; a struct with one of these
/// names would shadow it in its module.
const SHADOWED_TYPES: &[&str] = &["String", "Vec", "Option", "Result", "Box"];

impl Names {
    fn claim_type(&mut self, ident: &str, contract_name: &str) -> Result<String, String> {
        if SHADOWED_TYPES.contains(&ident) {
            return Err(format!(
                "contract name '{contract_name}' would shadow the Rust type '{ident}'"
            ));
        }
        self.claim(ident, contract_name)
    }

    fn claim(&mut self, ident: &str, contract_name: &str) -> Result<String, String> {
        if self.0.insert(ident.to_string()) {
            Ok(ident.to_string())
        } else {
            Err(format!(
                "contract name '{contract_name}' maps to the Rust identifier '{ident}', which is already used"
            ))
        }
    }
}

const RUST_KEYWORDS: &[&str] = &[
    "abstract", "as", "async", "await", "become", "box", "break", "const", "continue", "do", "dyn",
    "else", "enum", "extern", "false", "final", "fn", "for", "gen", "if", "impl", "in", "let",
    "loop", "macro", "match", "mod", "move", "mut", "override", "priv", "pub", "ref", "return",
    "static", "struct", "trait", "true", "try", "type", "typeof", "unsafe", "unsized", "use",
    "virtual", "where", "while", "yield",
];

/// Keywords that cannot be raw identifiers.
const RESERVED_PATH_KEYWORDS: &[&str] = &["crate", "self", "super", "Self", "_"];

fn snake_ident(name: &str) -> String {
    let mut ident = String::with_capacity(name.len());
    for (index, ch) in name.chars().enumerate() {
        if ch.is_ascii_uppercase() {
            if index > 0 && !ident.ends_with('_') {
                ident.push('_');
            }
            ident.push(ch.to_ascii_lowercase());
        } else if ch.is_ascii_alphanumeric() || ch == '_' {
            ident.push(ch);
        } else {
            ident.push('_');
        }
    }
    finish_ident(ident)
}

fn pascal_ident(name: &str) -> String {
    let mut ident = String::with_capacity(name.len());
    let mut upper = true;
    for ch in name.chars() {
        if ch.is_ascii_alphanumeric() {
            ident.push(if upper { ch.to_ascii_uppercase() } else { ch });
            upper = false;
        } else {
            upper = true;
        }
    }
    finish_ident(ident)
}

fn finish_ident(mut ident: String) -> String {
    if ident.is_empty() || ident.starts_with(|ch: char| ch.is_ascii_digit()) {
        ident.insert(0, '_');
    }
    if RESERVED_PATH_KEYWORDS.contains(&ident.as_str()) {
        ident.push('_');
        ident
    } else if RUST_KEYWORDS.contains(&ident.as_str()) {
        format!("r#{ident}")
    } else {
        ident
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::contract::parse_compiled_contract;
    use serde_json::json;

    #[test]
    fn identifiers_are_valid_rust_and_keep_their_wire_names() {
        assert_eq!(snake_ident("device_id"), "device_id");
        assert_eq!(snake_ident("artPath"), "art_path");
        assert_eq!(snake_ident("type"), "r#type");
        assert_eq!(snake_ident("self"), "self_");
        assert_eq!(snake_ident("2fa"), "_2fa");
        assert_eq!(snake_ident("kebab-name"), "kebab_name");
        assert_eq!(pascal_ident("VolumeChanged"), "VolumeChanged");
        assert_eq!(pascal_ident("wifi_network"), "WifiNetwork");
    }

    #[test]
    fn colliding_identifiers_are_reported() {
        let contract = parse_compiled_contract(
            "mesh.test",
            "1.0",
            &json!({ "state": { "artPath": "string", "art_path": "string" } }),
        )
        .unwrap();
        let error = generate_rust_bindings(&contract).unwrap_err();
        assert!(error.contains("'art_path'"), "{error}");
    }

    #[test]
    fn renamed_and_optional_fields_carry_serde_attributes() {
        let contract = parse_compiled_contract(
            "mesh.test",
            "1.0",
            &json!({ "state": {
                "artPath": "string?",
                "type": "int",
                "source_module": "string"
            } }),
        )
        .unwrap();
        let bindings = generate_rust_bindings(&contract).unwrap();
        assert!(bindings.contains(
            "    #[serde(rename = \"artPath\")]\n    #[serde(default, skip_serializing_if = \"Option::is_none\")]\n    pub art_path: Option<String>,\n"
        ));
        assert!(bindings.contains("    pub r#type: i64,\n"));
        assert!(!bindings.contains("source_module"));
    }

    #[test]
    fn blob_fields_use_a_handle_newtype_only_when_declared() {
        let with_blob = parse_compiled_contract(
            "mesh.test",
            "1.0",
            &json!({
                "state": { "items": "Item[]" },
                "types": { "Item": { "icon": "blob?" } }
            }),
        )
        .unwrap();
        let bindings = generate_rust_bindings(&with_blob).unwrap();
        assert!(bindings.contains("pub struct BlobHandle(pub String);"));
        assert!(bindings.contains("pub icon: Option<super::BlobHandle>,"));

        let without = parse_compiled_contract(
            "mesh.test",
            "1.0",
            &json!({ "state": { "level": "int" } }),
        )
        .unwrap();
        assert!(!generate_rust_bindings(&without).unwrap().contains("BlobHandle"));
    }
}
